TEMPLATE = pathlib.Path(__file__).parent / "template"
DEFAULT_MC = '["1.26.*"]'   # same default as the official template's CMakeLists.txt
PRIM = {"Z": ("bool", "false"), "I": ("int", "0"), "J": ("long long", "0"),
        "S": ("int", "0"), "B": ("int", "0"), "F": ("double", "0"), "D": ("double", "0"),
        "Ljava/lang/String;": ("std::string", '""')}


CPP_RESERVED = set("""alignas alignof and and_eq asm auto bitand bitor bool break case catch char class compl concept
const consteval constexpr constinit const_cast continue co_await co_return co_yield decltype default delete do double
dynamic_cast else enum explicit export extern false float for friend goto if inline int long mutable namespace new
noexcept not not_eq nullptr operator or or_eq private protected public register reinterpret_cast requires return short
signed sizeof static static_assert static_cast struct switch template this thread_local throw true try typedef typeid
typename union unsigned using virtual void volatile wchar_t while xor xor_eq NULL nan inf version enabled message""".split())
MAX_STRING_LEN = 160
MAX_CONFIG_FIELDS = 64    # boost::pfr reflection limit safety margin


def ident(s):
    s = re.sub(r"[^0-9A-Za-z_]", "_", s)
    return ("m_" + s) if not s or s[0].isdigit() else s


def pascal(s):
    return "".join(p.capitalize() for p in re.split(r"[^0-9A-Za-z]+", s) if p) or "Mod"


def snake(s):
    s = re.sub(r"(?<=[a-z0-9])([A-Z])", r"_\1", s)
    return re.sub(r"[^0-9a-zA-Z]+", "_", s).strip("_").lower() or "value"


def load_jar(path):
    classes, files = {}, {}
    with zipfile.ZipFile(path) as z:
        for n in z.namelist():
            if n.endswith("/"):
                continue
            data = z.read(n)
            if n.endswith(".class") and not n.startswith("META-INF/"):
                try:
                    cf = C.parse(data); classes[cf.name] = cf
                except Exception as e:      # keep going, report later
                    files[n + ".unparsed"] = str(e).encode()
            else:
                files[n] = data
    return classes, files


def clinit_constants(cf):
    """Return {field: constant tuple} for `const; putstatic` pairs in <clinit>."""
    m = cf.find_method("<clinit>")
    out = {}
    if not m or not m.code:
        return out
    last = None
    for i in C.decode(m.code):
        if i.op in (2, 3, 4, 5, 6, 7, 8): last = ("int", i.op - 3)
        elif i.op in (16, 17): last = ("int", i.arg)
        elif i.op in (18, 19, 20):
            v = cf.const(i.arg); last = v if isinstance(v, tuple) else ("str", v)
        elif i.op == 179 and last is not None:
            o, n, d = cf.ref(i.arg)
            if o == cf.name: out[n] = last
            last = None
        else:
            last = None
    return out


def collect_config(classes, entry_classes, reserve=0):
    fields = {}   # (owner, name) -> dict
    used = {"version", "enabled", "message"}
    for cf in classes.values():
        cfgish = any(k in cf.name.lower() for k in ("config", "settings", "options")) or cf.name in entry_classes
        init = clinit_constants(cf)
        for f in cf.fields:
            if not (f.access & 0x0008) or f.desc not in PRIM:   # static + supported type
                continue
            final = bool(f.access & 0x0010)
            val = f.const_value if f.const_value is not None else init.get(f.name)
            if val is None or (final and not cfgish):
                continue
            if val[0] in ("float", "double") and not math.isfinite(val[1]):
                continue          # NaN/Infinity cannot be stored in JSON config
            if val[0] == "str" and len(val[1]) > MAX_STRING_LEN:
                continue          # long text blobs are not settings; keep config.json small
            if len(fields) >= MAX_CONFIG_FIELDS - reserve:
                continue
            name = snake(f.name)
            while name in used or name in CPP_RESERVED: name += "_"
            used.add(name)
            fields[(cf.name, f.name)] = {"member": name, "desc": f.desc, "value": val,
                                         "java": f"{cf.name.replace('/', '.')}.{f.name}"}
    return fields


def cpp_default(desc, val):
    k, v = val
    if desc == "Z": return "true" if v else "false"
    if desc == "Ljava/lang/String;": return cstr(v) if k == "str" else '""'
    if k in ("float", "double"): return repr(float(v))
    if desc == "J":
        return "(-9223372036854775807LL - 1)" if v == -9223372036854775808 else f"{v}LL"
    return str(v)


def convert(jar, out, mc_versions=None, symbols=None, mod_id=None):
    out = pathlib.Path(out)
    classes, files = load_jar(jar)
    if "fabric.mod.json" not in files:
        raise SystemExit("not a Fabric mod: fabric.mod.json missing in jar root")
    meta = fabricmeta.parse(files["fabric.mod.json"].decode("utf-8-sig"))
    mid = ident(mod_id or meta["id"]).lower()
    base = pascal(mid)
    ns, cls = mid, base if base.endswith("Mod") else base + "Mod"
    sym = SymbolIndex.load(symbols)      # always has the bundled build-keyed vtable DB

    entry_classes = {c for kind in ("main", "client", "server") for c, _ in meta["entrypoints"].get(kind, [])}
    commands, cmd_classes = cmdmod.find_commands(classes)
    cmd_fields = cmdmod.config_fields(commands)
    cfg = collect_config(classes, entry_classes, reserve=len(cmd_fields))
    cfg_names = {k: v["member"] for k, v in cfg.items()}

    tp = Transpiler(classes, symbols=sym, cfg_fields=cfg_names, meta=meta, mod_id=meta["id"],
                    cmd_classes=cmd_classes, commands=commands)
    entry_report = []
    for kind in ("main", "client", "server"):
        for c, meth in meta["entrypoints"].get(kind, []):
            cf = classes.get(c)
            if not cf:
                tp.res.issues.append({"where": c, "what": "entrypoint class missing"}); continue
            mn = meth or {"main": "onInitialize", "client": "onInitializeClient", "server": "onInitializeServer"}[kind]
            entry_report.append(f"{kind}: {c.replace('/', '.')}.{mn}")
            tp.res.enable.append(f"// --- entrypoint [{kind}] {c.replace('/', '.')}.{mn}")
            tp.entry(c, mn, "enable")
    res = tp.res

    # ---------- project skeleton from the official template
    if out.exists():
        shutil.rmtree(out)
    shutil.copytree(TEMPLATE, out, ignore=shutil.ignore_patterns("build.yml", "gitignore.txt"))
    (out / "manifest.json.in").write_text(TEMPLATES["manifest.json"])
    (out / ".gitignore").write_text("build*/\nconfig/\n.cache/\n")
    (out / ".github/workflows").mkdir(parents=True, exist_ok=True)
    if (TEMPLATE / "build.yml").exists():
        shutil.copy(TEMPLATE / "build.yml", out / ".github/workflows/build.yml")

    mc = mc_versions or DEFAULT_MC
    library = re.sub(r"[^0-9A-Za-z_]", "_", mid)
    icon_rel = ""
    if meta["icon"] and meta["icon"] in files:
        icon_rel = "icon" + pathlib.Path(meta["icon"]).suffix
        (out / icon_rel).write_bytes(files[meta["icon"]])

    cm = (out / "CMakeLists.txt").read_text()
    for key, val in (("MOD_ID", mid), ("MOD_NAME", meta["name"]), ("MOD_AUTHOR", ", ".join(meta["authors"]) or mid),
                     ("MOD_VERSION", meta["version"]), ("MOD_LIBRARY_NAME", library)):
        cm = re.sub(rf'set\({key} "[^"]*" CACHE', lambda m, v=val, k=key: f'set({k} "{v}" CACHE', cm)
    cm = re.sub(r'set\(MOD_MINECRAFT_VERSIONS "[^\n]*?" CACHE',
                lambda m: 'set(MOD_MINECRAFT_VERSIONS "' + mc.replace('"', '\\"') + '" CACHE', cm)
    cm = re.sub(r'set\(MOD_ICON "[^"]*" CACHE', lambda m: f'set(MOD_ICON "{icon_rel}" CACHE', cm)
    # experimental: ship converted Java assets (lang files) next to the library
    cm = cm.replace("set(LEVI_PACKAGE_ICON_COMMAND)",
                    "set(LEVI_PACKAGE_ICON_COMMAND)\nset(LEVI_PACKAGE_RESOURCES_COMMAND)\n"
                    "if(IS_DIRECTORY \"${CMAKE_CURRENT_SOURCE_DIR}/resources\")\n"
                    "    set(LEVI_PACKAGE_RESOURCES_COMMAND\n"
                    "        COMMAND \"${CMAKE_COMMAND}\" -E copy_directory \"${CMAKE_CURRENT_SOURCE_DIR}/resources\" \"${LEVI_PACKAGE_MOD_DIR}/resources\")\n"
                    "endif()")
    cm = cm.replace("    ${LEVI_PACKAGE_CONFIG_COMMAND}\n    COMMAND", "    ${LEVI_PACKAGE_CONFIG_COMMAND}\n    ${LEVI_PACKAGE_RESOURCES_COMMAND}\n    COMMAND")
    (out / "CMakeLists.txt").write_text(cm)

    # ---------- sources
    def tpl(name, **kw):
        s = TEMPLATES[name]
        for k, v in kw.items():
            s = s.replace(f"@{k}@", v)
        return s

    cfg_lines, schema_lines = [], []
    for (o, n), f in cfg.items():
        t, _ = PRIM[f["desc"]]
        cfg_lines.append(f"    {t} {f['member']} = {cpp_default(f['desc'], f['value'])}; // {f['java']}")
        schema_lines.append(f'        if (name == "{f["member"]}")\n'
                            f'            return {{.title = {cstr(f["member"].replace("_", " ").title())}, '
                            f'.description = {cstr("Imported from Java field " + f["java"])}}};')
    taken = {f["member"] for f in cfg.values()} | {"version", "enabled", "message"}
    for f in cmd_fields:
        while f["member"] in taken:
            f["member"] += "_"
        taken.add(f["member"])
        cfg_lines.append(f"    {f['type']} {f['member']} = {f['default']}; // command")
        schema_lines.append(f'        if (name == "{f["member"]}")\n'
                            f'            return {{.title = {cstr(f["title"])}, .description = {cstr(f["desc"])}}};')
    indent = lambda ls: "\n".join("    " + l for l in ls) if ls else "    // (nothing converted)"
    (out / "src/mod").mkdir(parents=True, exist_ok=True)
    res.enable.append("hooks::installAll(self);")
    res.disable.append("hooks::uninstallAll(self);")
    kw = dict(NS=ns, CLS=cls, MODNAME=meta["name"], MODID=mid, TITLE=cstr(meta["name"] + " Config"),
              CONFIG_FIELDS="\n".join(cfg_lines), SCHEMA_FIELDS="\n".join(schema_lines),
              ENABLE_BODY=indent(res.enable), DISABLE_BODY=indent(res.disable))
    for n in ("MyMod.h", "MyMod.cpp", "Config.h", "Config.cpp"):
        (out / "src/mod" / n).write_text(tpl(n, **kw))
    hh, hc = hookmod.render(ns, res.issues, commands, sym)
    rh, rc = hookmod.render_resolve(ns)
    (out / "src/mod/Hooks.h").write_text(hh)
    (out / "src/mod/Hooks.cpp").write_text(hc)
    (out / "src/mod/Resolve.h").write_text(rh)
    (out / "src/mod/Resolve.cpp").write_text(rc)
    cm2 = (out / "CMakeLists.txt").read_text()
    assert cm2.count("    src/mod/MyMod.cpp") == 1
    (out / "CMakeLists.txt").write_text(cm2.replace("    src/mod/MyMod.cpp", "    src/mod/MyMod.cpp\n    src/mod/Hooks.cpp\n    src/mod/Resolve.cpp"))
    for n in ("main.cpp", "config_generator.cpp"):
        s = (out / "src" / n).read_text().replace("ClangeMeMod", cls).replace("clange_me", ns)
        (out / "src" / n).write_text(s)

    # ---------- assets: Java lang json -> .lang (experimental)
    lang_out = []
    for n, data in files.items():
        m = re.match(r"assets/[^/]+/lang/([a-z]{2})_([a-z]{2})\.json$", n)
        if m:
            try:
                j = json.loads(data.decode("utf-8"))
            except Exception:
                continue
            lines = [f"{k}={str(v).replace(chr(10), ' ')}" for k, v in j.items() if isinstance(v, str)]
            p = out / "resources/texts" / f"{m.group(1)}_{m.group(2).upper()}.lang"
            p.parent.mkdir(parents=True, exist_ok=True)
            p.write_text("\n".join(lines) + "\n", encoding="utf-8"); lang_out.append(p.name)

    # ---------- report
    extra_resolved = []
    if "modmenu" in meta["entrypoints"]:
        extra_resolved.append({"where": "fabric.mod.json entrypoints.modmenu", "what": "Mod Menu config screen",
                               "how": "replaced by the typed config the launcher shows (config.json + schema)"})
    mixin_configs = meta.get("mixins", [])
    # Mixin JSON/class metadata is inventoried explicitly. Mixin bytecode is not Java-runtime
    # compatible with Bedrock, so emit native-port tasks rather than silently ignoring it.
    mixin_class_names = set()
    for entry in mixin_configs:
        cfg_path = entry if isinstance(entry, str) else entry.get("config", "")
        if not cfg_path or cfg_path not in files:
            res.issues.append({"where": str(cfg_path or entry), "what": "Mixin configuration file is missing from the JAR", "kind": "manual",
                               "category": "Mixin metadata", "fix": "Check the fabric.mod.json mixin declaration and include the referenced JSON config in the JAR."})
            res.stubbed += 1
            continue
        try:
            mixin_doc = json.loads(files[cfg_path].decode("utf-8-sig"))
        except Exception:
            continue
        package = mixin_doc.get("package", "")
        for key in ("mixins", "client", "server"):
            for cls_name in mixin_doc.get(key, []) or []:
                if isinstance(cls_name, str):
                    full = ".".join(x for x in (package, cls_name) if x).replace(".", "/")
                    mixin_class_names.add(full)
    for cls_name in sorted(mixin_class_names):
        res.issues.append({"where": cls_name, "what": "Mixin injection requires a Bedrock-native equivalent", "kind": "gap",
                           "category": "Mixin injection", "fix": "Port the injection's intent to a verified Bedrock function hook using <pl/memory/Hook.hpp>; inspect the mixin target, injection point, locals and cancellation semantics before implementing."})
        res.stubbed += 1
    gaps = [i for i in res.issues if i["kind"] == "gap"]
    manual = [i for i in res.issues if i["kind"] != "gap"]
    asset_files = sorted(n for n in files if n.startswith(("assets/", "data/")) and not n.endswith(".class"))
    asset_counts = {"textures": sum(1 for n in asset_files if n.endswith((".png", ".tga", ".jpg", ".jpeg"))),
                    "models": sum(1 for n in asset_files if "/models/" in n or n.endswith((".bbmodel", ".geo.json"))),
                    "data_pack_files": sum(1 for n in asset_files if n.startswith("data/"))}
    rep = [f"# Conversion report: {meta['name']} ({meta['version']})", "",
           f"* Fabric mod id: `{meta['id']}`  ->  C++ namespace `{ns}`, class `{cls}`",
           f"* Entrypoints: {', '.join(entry_report) or 'none found'}",
           f"* Java classes in jar: {len(classes)}; methods fully converted: {res.converted}; "
           f"stubs left for manual work: {res.stubbed}",
           f"* Handled automatically: {len(res.resolved) + len(extra_resolved)}; "
           f"need a native game hook: {len(gaps)}; plain logic to port: {len(manual)}",
           f"* Config fields imported from static Java fields: {len(cfg)}",
           f"* Language files converted: {', '.join(lang_out) or 'none'}",
           f"* Asset inventory (not automatically ported): {asset_counts}",
           f"* Mixin configs declared: {len(mixin_configs)}; mixin classes inventoried: {len(mixin_class_names)}", "",
           "## Mixin classes requiring native ports",
           *([f"- `{n}`" for n in sorted(mixin_class_names)] or ["- No mixin classes found"]), "",
           "## Java asset inventory (not shipped)",
           "This build intentionally has no Bedrock resource-pack dependency. Textures, models and data-pack files are inventoried below, but cannot appear in-game without a Bedrock-compatible asset implementation. See `docs/ASSET_PORTING.md`.",
           *([f"- `{n}`" for n in asset_files[:300]] or ["- No assets/data files found"]),
           *( [f"- ... and {len(asset_files) - 300} more files" ] if len(asset_files) > 300 else [] ), "",
           "## What converted automatically",
           "Straight-line entrypoint code: logger / System.out calls, Fabric lifecycle events "
           "(started/stopping -> `enable()` / `disable()`), static constants -> typed config.", ""]
    rep.append("### Auto-resolved (no manual work)")
    for it in res.resolved + extra_resolved:
        rep.append(f"* `{it['what']}` - {it['how']}")
    if not (res.resolved or extra_resolved):
        rep.append("* nothing")
    rep += ["", "## What needs manual work"]
    if not res.issues:
        rep.append("* nothing flagged")
    for title, items in (("Needs a native game hook", gaps), ("Plain logic / bytecode to port", manual)):
        if not items:
            continue
        rep += ["", f"### {title}"]
        for it in items:
            rep.append(f"* `{it['where']}` - {it['what']}")
            rep.append(f"  * **{it['category']}**: {it['fix']}")
    rep += ["", "## Mod menu",
            "Every generated mod includes a launcher-editable settings menu backed by typed `config.json` and schema. "
            "Imported static settings and detected command options are exposed as fields; unsupported Java behavior is not falsely represented as working settings.",
            "", "## Native hooks",
            "`src/mod/Hooks.cpp` lists every gap above as a hook entry (with Bedrock symbol candidates when `--symbols` is given); "
            "it is logged at start-up. Targets with static evidence in the bundled symbol DB are resolved and prologue-checked at "
            "start-up (`Resolve.cpp`); everything else stays a logged TODO. Client commands were turned into `cmd_*` launcher config fields "
            f"({len(cmd_fields)} fields from {len(commands)} commands).",
            "", "## How to solve the open items",
            "Use MANUAL_WORK.md as the implementation checklist. Verify each candidate against the exact Bedrock build before enabling a detour; unresolved calls remain safe TODOs.",
            "", "## Not converted (by design)",
            "Mixin injection semantics, Minecraft Java API calls, textures/models/data packs are inventoried and emitted as native-port tasks, not translated blindly. "
            "Bedrock has no Java classes; every game-facing call needs a native hook via `<pl/memory/Hook.hpp>` "
            "(see the symbol candidates printed next to each TODO when `--symbols` is supplied)."]
    (out / "CONVERSION_REPORT.md").write_text("\n".join(rep) + "\n")

    # ---------- MANUAL_WORK.md: implementation checklist (no overrides directory/files)
    mw = [f"# Native implementation checklist for {meta['name']}", "",
          "The converter emits safe hook stubs. Implement and verify each item in the generated native project; no overrides directory or external fix file is required.", ""]
    by_cat = {}
    for it in res.issues:
        by_cat.setdefault(it["category"], []).append(it)
    for cat, items in sorted(by_cat.items()):
        mw += [f"## {cat} ({len(items)})", "", items[0]["fix"], ""]
        mw += [f"- [ ] `{i['what']}`  (in `{i['where']}`)" for i in items]
        mw.append("")
    if not res.issues:
        mw.append("Nothing to do.")
    (out / "MANUAL_WORK.md").write_text("\n".join(mw) + "\n")
    (out / "levipack.project.json").write_text(json.dumps(
        {"source_jar": pathlib.Path(jar).name, "mod_id": mid, "minecraft_versions": json.loads(mc),
         "forge_version": __import__("levipack_forge").__version__, "symbol_db_build": sym.db.tag,
         "mod_menu": {"type": "launcher_config", "config": "config.json", "schema": "config.schema.json"},
         "resource_pack_required": False}, indent=2) + "\n")
    (out / "README.md").write_text(
        f"# {meta['name']} (LeviLauncher Android port)\n\nGenerated by levipack-forge from a Fabric mod.\n"
        f"Read `CONVERSION_REPORT.md` first, finish the `TODO(levipack-forge)` items in `src/mod/MyMod.cpp`,\n"
        f"then build with `./scripts/package.ps1 -Abi all` or push to GitHub (Actions builds the `.levipack`).\n")
    return {"out": str(out), "issues": res.issues, "converted": res.converted, "stubbed": res.stubbed,
            "config_fields": len(cfg) + len(cmd_fields), "mod_menu": True, "resource_pack_required": False, "mod_id": mid, "resolved": len(res.resolved) + len(extra_resolved)}
