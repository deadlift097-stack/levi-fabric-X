"""Native hook registry: one entry per Java feature that needs a Bedrock hook.

Only documented, compile-safe C++ is generated (no guessing of SDK macros). The registry
* logs every un-installed hook at start-up so gaps are visible in the launcher log,
* lists Bedrock symbol candidates (from --symbols) next to each feature,
* has a single marked place (HOOK-POINT) per feature where the hook is installed with
  `<pl/memory/Hook.hpp>` once the symbol is verified against the exact Bedrock version.
* v0.4: when the bundled symbol DB has a *statically verified* vtable slot for the feature, the registry resolves
  its address at start-up (`Resolve.cpp`, plain C++, no SDK) and refuses it unless the function's first
  instructions match what was read from the analysed libminecraftpe.so. `h.address` is then safe to hook.
"""
from __future__ import annotations
import re
from .transpile import cstr

H = '''#pragma once

#include <pl/Mod.hpp>

namespace @NS@::hooks {

// Installs every native hook that has been wired up; logs the ones that still need work.
void installAll(ll::mod::NativeMod &self);
void uninstallAll(ll::mod::NativeMod &self);

} // namespace @NS@::hooks
'''

CPP = '''// Generated by levipack-forge. One row per Java feature that has no automatic Bedrock equivalent.
#include "mod/Hooks.h"
#include "mod/Resolve.h"

#include <pl/memory/Hook.hpp>
#include <pl/memory/Vtable.hpp>

#include <algorithm>
#include <array>
#include <atomic>
#include <cstddef>
#include <cstdint>
#include <string>
#include <string_view>
#include <utility>
#include <vector>

namespace @NS@::hooks {
namespace {

constexpr std::string_view kGameLib = "libminecraftpe.so";
constexpr size_t kMaxHooks = 16; // distinct addresses hooked per target (base slot + subclass overrides)

// Handy inside diagnostic/custom native hook bodies: modLog().info("...", x);
inline auto &modLog() { return ll::mod::NativeMod::current()->getLogger(); }

// ---- detours. One template instance per hooked address: each address has its own trampoline, and the detour
// must call the trampoline of the function that was actually entered (a subclass override is not the base function).
// Body defaults to pass-through; the dedicated live-test generator can inject a diagnostic body. In a body you have
// `orig(...)`, `self`, `a0`, `a1`, ...  (this = `self`).
@DETOURS@
// ---- statically verified virtual functions of libminecraftpe.so build @BUILD@ (levipack-forge symbol DB).
// `expect` = the first instruction words read from that binary; resolve:: refuses a slot that does not match, so another
// game build degrades to "feature skipped" instead of a crash.
struct Extra {                 // a subclass vtable that overrides the same slot (see tools/so_probe.py --subclasses)
    uint64_t vptrRva;
    std::vector<uint32_t> expect;
};
struct Target {
    std::string_view name;
    std::string_view rtti;     // Itanium typeinfo name of the owning class, e.g. "4Item"
    uint64_t vptrRva;
    uint32_t slot;
    std::vector<uint32_t> expect;
    std::vector<Extra> extras;
    std::array<void *, kMaxHooks> (*detours)();
    void **origs;              // trampolines, filled by pl::memory::hook
    bool ported;               // true when the hook body comes from overrides (the Java behaviour is implemented)
};

const std::vector<Target> &targets() {
    static const std::vector<Target> t = {
@TARGETS@
    };
    return t;
}

struct HookInfo {
    std::string_view feature;     // what the Java mod did
    std::string_view category;    // kind of work (commands, rendering, ...)
    std::string_view how;         // suggested way to solve it
    std::vector<std::string_view> symbols; // Bedrock symbol candidates (heuristic, verify before hooking)
    bool installed;
    std::string_view target = {}; // name of a statically verified vtable slot in targets() ("" = none known)
    uintptr_t address = 0;        // filled by installAll(): validated function address, 0 = not resolved
};

std::vector<HookInfo> &table() {
    static std::vector<HookInfo> t = {
@ROWS@
    };
    return t;
}

struct Live {
    void *target;
    void *detour;
};
std::vector<Live> &live() {
    static std::vector<Live> v;
    return v;
}

// Installs the detours of one target. Returns how many addresses were hooked.
size_t hookTarget(ll::mod::NativeMod &self, const resolve::Module &game, const Target &t, uintptr_t &baseAddr) {
    const auto name = std::string(t.name);
    baseAddr = resolve::virtualTarget(game, t.vptrRva, t.slot, t.expect.data(), t.expect.size());
    if (!baseAddr) {
        self.getLogger().warn("[hook] {} does not match game build @BUILD@; feature skipped", name);
        return 0;
    }
    // Independent cross-check with the preloader's own RTTI resolver (same slot numbering): never hook on disagreement.
    const uintptr_t sdk = pl::memory::resolveVtableFunction(t.rtti, t.slot, kGameLib);
    if (sdk && sdk != baseAddr) {
        self.getLogger().error("[hook] {}: preloader resolves 0x{:x}, levipack-forge 0x{:x}; refusing to hook", name,
                               static_cast<uint64_t>(sdk), static_cast<uint64_t>(baseAddr));
        return 0;
    }
    if (!sdk)
        self.getLogger().debug("[hook] {}: preloader could not cross-check the slot (RTTI lookup returned 0)", name);

    std::vector<uintptr_t> addrs{baseAddr};
    for (const auto &e : t.extras) {
        const uintptr_t a = resolve::virtualTarget(game, e.vptrRva, t.slot, e.expect.data(), e.expect.size());
        if (a && std::find(addrs.begin(), addrs.end(), a) == addrs.end())
            addrs.push_back(a);
    }
    if (addrs.size() > kMaxHooks) {
        self.getLogger().warn("[hook] {}: {} distinct overrides, hooking the first {}", name, addrs.size(), kMaxHooks);
        addrs.resize(kMaxHooks);
    }
    const auto detours = t.detours();
    size_t ok = 0;
    for (size_t i = 0; i < addrs.size(); ++i) {
        void *target = reinterpret_cast<void *>(addrs[i]);
        if (pl::memory::hook(target, detours[i], &t.origs[i]) == 0) {
            live().push_back({target, detours[i]});
            ++ok;
        } else {
            self.getLogger().error("[hook] {}: pl::memory::hook failed at base+0x{:x}", name,
                                   static_cast<uint64_t>(addrs[i] - game.base));
        }
    }
    self.getLogger().info("[hook] {}: {} of {} address(es) hooked ({} subclass override(s))", name, ok, addrs.size(),
                          addrs.size() - 1);
    return ok;
}

} // namespace

void installAll(ll::mod::NativeMod &self) {
    size_t pending = 0, hooked = 0;
    const resolve::Module game = resolve::findModule(kGameLib);
    std::vector<std::string_view> done;
    for (auto &h : table()) {
        if (!h.target.empty()) {
            if (!game.base) {
                self.getLogger().warn("{} is not mapped; native hooks are skipped", std::string(kGameLib));
            } else if (std::find(done.begin(), done.end(), h.target) == done.end()) {
                done.push_back(h.target);
                for (const auto &t : targets()) {
                    if (t.name != h.target)
                        continue;
                    if (hookTarget(self, game, t, h.address) && t.ported)
                        h.installed = true;
                    hooked += h.address != 0;
                }
            }
        }
        if (!h.installed) {
            ++pending;
            self.getLogger().debug("[hook] not ported: {} ({})", std::string(h.feature), std::string(h.category));
        }
    }
    if (hooked)
        self.getLogger().info("{} hook target(s) resolved, prologue-checked and hooked", hooked);
    if (pending)
        self.getLogger().warn("{} Java feature(s) are not ported to native hooks yet (see CONVERSION_REPORT.md)", pending);
}

void uninstallAll(ll::mod::NativeMod &self) {
    for (auto &l : live())
        pl::memory::unhook(l.target, l.detour);
    live().clear();
    for (auto &t : targets())
        for (size_t i = 0; i < kMaxHooks; ++i)
            t.origs[i] = nullptr;
    for (auto &h : table()) {
        h.installed = false;
        h.address = 0;
    }
    self.getLogger().debug("hooks released");
}

} // namespace @NS@::hooks
'''


RESOLVE_H = '''#pragma once
// Generated by levipack-forge. Plain C++17 / POSIX: no preloader or game headers needed.
#include <cstddef>
#include <cstdint>
#include <string_view>

namespace @NS@::resolve {

struct Module {
    uintptr_t base = 0; // load address (the lowest mapping, file offset 0). 0 = library not found
    uintptr_t end = 0;  // one past the highest mapping of the library
};

// Parse the text of /proc/self/maps. A library whose lowest mapping has a non-zero file offset is rejected.
Module findModuleInMaps(std::string_view mapsText, std::string_view libName);
// Same, for the running process.
Module findModule(std::string_view libName);

// True if `n` 32-bit instruction words at `addr` equal `expect`.
bool wordsMatch(uintptr_t addr, const uint32_t *expect, size_t n);

// Itanium vtable: slot value = *(base + vptrRva + 8 * slot). Returns the function address, or 0 when the slot lies
// outside the module, the target is outside the module, or its first instructions differ from `expect`.
// n == 0 skips the instruction check (do not hook such a target without another proof).
uintptr_t virtualTarget(const Module &m, uint64_t vptrRva, uint32_t slot, const uint32_t *expect, size_t n);

} // namespace @NS@::resolve
'''

RESOLVE_CPP = '''// Generated by levipack-forge. See Resolve.h.
#include "mod/Resolve.h"

#include <cstdio>
#include <cstdlib>
#include <cstring>
#include <fstream>
#include <sstream>
#include <string>

namespace @NS@::resolve {

Module findModuleInMaps(std::string_view maps, std::string_view lib) {
    Module m;
    bool lowestHasOffsetZero = false;
    size_t pos = 0;
    while (pos < maps.size()) {
        size_t eol = maps.find('\\n', pos);
        if (eol == std::string_view::npos)
            eol = maps.size();
        const std::string line(maps.substr(pos, eol - pos));
        pos = eol + 1;
        if (line.size() < lib.size() || line.compare(line.size() - lib.size(), lib.size(), lib) != 0)
            continue;
        unsigned long long lo = 0, hi = 0, off = 0;
        if (std::sscanf(line.c_str(), "%llx-%llx %*4s %llx", &lo, &hi, &off) != 3 || hi <= lo)
            continue;
        if (m.base == 0 || lo < m.base) {
            m.base = static_cast<uintptr_t>(lo);
            lowestHasOffsetZero = (off == 0);
        }
        if (hi > m.end)
            m.end = static_cast<uintptr_t>(hi);
    }
    if (!lowestHasOffsetZero)
        return {};
    return m;
}

Module findModule(std::string_view lib) {
    std::ifstream f("/proc/self/maps");
    std::stringstream ss;
    ss << f.rdbuf();
    return findModuleInMaps(ss.str(), lib);
}

bool wordsMatch(uintptr_t addr, const uint32_t *expect, size_t n) {
    for (size_t i = 0; i < n; ++i) {
        uint32_t w = 0;
        std::memcpy(&w, reinterpret_cast<const void *>(addr + 4 * i), sizeof w);
        if (w != expect[i])
            return false;
    }
    return true;
}

uintptr_t virtualTarget(const Module &m, uint64_t vptrRva, uint32_t slot, const uint32_t *expect, size_t n) {
    if (!m.base)
        return 0;
    const uint64_t slotOff = vptrRva + 8ull * slot;
    if (m.base + slotOff + 8 > m.end || m.base + slotOff < m.base)
        return 0;
    uintptr_t fn = 0;
    std::memcpy(&fn, reinterpret_cast<const void *>(m.base + slotOff), sizeof fn);
    if (fn < m.base || fn + 4 * n > m.end)
        return 0;
    if (n && !wordsMatch(fn, expect, n))
        return 0;
    return fn;
}

} // namespace @NS@::resolve
'''


def render_resolve(ns):
    return RESOLVE_H.replace("@NS@", ns), RESOLVE_CPP.replace("@NS@", ns)


def _san(name):
    return re.sub(r"[^0-9A-Za-z]+", "_", name)


def _detour_block(name, f, body):
    ns_ = "hk_" + _san(name)
    ret = f["cpp_ret"]
    params = f.get("cpp_params", [])
    sig = ", ".join(["void *self"] + [f"{t} a{i}" for i, t in enumerate(params)])
    types = ", ".join(["void *"] + params)
    call = ", ".join(["self"] + [f"a{i}" for i in range(len(params))])
    if body is None:
        body = f"{'return ' if ret != 'void' else ''}orig({call});"
    return (f"namespace {ns_} {{\n"
            f"using Fn = {ret} (*)({types});\n"
            f"Fn origs[kMaxHooks] = {{}};\n"
            f"template <size_t K> {ret} fn({sig}) {{\n"
            f"    [[maybe_unused]] const Fn orig = origs[K];\n"
            f"    {body}\n}}\n"
            f"template <size_t... K> std::array<void *, kMaxHooks> make(std::index_sequence<K...>) {{\n"
            f"    return {{reinterpret_cast<void *>(&fn<K>)...}};\n}}\n"
            f"std::array<void *, kMaxHooks> detours() {{ return make(std::make_index_sequence<kMaxHooks>{{}}); }}\n"
            f"}} // namespace {ns_}\n"), ns_


def render(ns, issues, commands, sym=None, hook_overrides=None):
    """hook_overrides: {"Item::getAttackDamage": {"cpp": "return orig(self) + 3;"}} - forces the target into the
    hook table and replaces the pass-through body (survives re-conversion like the other overrides)."""
    hook_overrides = hook_overrides or {}
    rows, seen, wanted = [], set(), []
    for it in issues:
        key = it["what"]
        if key in seen:
            continue
        seen.add(key)
        syms = sym.hints_for(it["what"]) if sym is not None else []
        tg = sym.targets_for(it["what"]) if sym is not None else []
        sl = ", ".join(cstr(s) for s in syms)
        tail = ""
        if tg:
            tail = f", {cstr(tg[0])}"
            if tg[0] not in wanted:
                wanted.append(tg[0])
        rows.append(f'        {{{cstr(it["what"])}, {cstr(it["category"])}, {cstr(it["fix"])}, {{{sl}}}, false{tail}}},')
    for name in hook_overrides:
        if sym is None or not sym.db.usable(name):
            raise ValueError(f"hooks override '{name}': no statically verified slot for it in the symbol DB "
                             f"(usable: {', '.join(sorted(n for n in sym.db.functions if sym.db.usable(n))) if sym else 'none'})")
        if name not in wanted:
            wanted.append(name)
            rows.append(f'        {{{cstr("hooks override " + name)}, "Native hook", '
                        f'"Implemented by the dedicated native diagnostic hook body", {{}}, false, {cstr(name)}}},')
    for c in commands:
        what = f"command /{c['path']} -> config cmd_* field (value is stored; a hook must apply it)"
        rows.append(f'        {{{cstr(what)}, "Commands", "Apply the stored config value inside the hook that implements this feature.", {{}}, false}},')
    body = "\n".join(rows) if rows else "        // (nothing to hook)"
    detours, trows = [], []
    for name in wanted:
        f = sym.db.functions[name]
        ov = hook_overrides.get(name) or {}
        blk, dns = _detour_block(name, f, ov.get("cpp"))
        detours.append(blk)
        words = ", ".join(w + "u" for w in f["expect"])
        extras = ", ".join("{%dull, {%s}}" % (int(x["vptr_rva"], 16), ", ".join(w + "u" for w in x["expect"]))
                           for x in sym.db.overrides_for(name))
        vt = f["vtable"]
        trows.append(f'        {{{cstr(name)}, {cstr(str(len(vt)) + vt)}, {sym.db.vptr_rva(vt)}ull, {f["index"]}, '
                     f'{{{words}}}, {{{extras}}}, &{dns}::detours, reinterpret_cast<void **>({dns}::origs), '
                     f'{"true" if ov.get("cpp") else "false"}}},')
    tbody = "\n".join(trows) if trows else "        // (no statically verified target needed by this mod)"
    build = sym.db.tag if sym is not None else "unknown"
    cpp = (CPP.replace("@NS@", ns).replace("@ROWS@", body).replace("@TARGETS@", tbody)
              .replace("@DETOURS@", "\n".join(detours)).replace("@BUILD@", build))
    return H.replace("@NS@", ns), cpp
